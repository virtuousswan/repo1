#include<stdio.h>
#include<math.h>

// dy/dx = (y - x) / (y + x)
// #define f(x, y) ((y - x) / (y + x))
float f(float x, float y)
{
    return (y - x) / (y + x);
}

int main()
{
    float x0, y0, xn, h, x1, y1;
    int i = 0, n;

    printf("Enter x0, y0, h and xn: ");
    scanf("%f %f %f %f", &x0, &y0, &h, &xn);
    //x0=0  y0=1  h=0.02  xn=0.1  

    // Number of steps
    n = (xn - x0) / h;
//   = (0.1 - 0) / 0.02
//   = 0.1 / 0.02
//   = 5



    printf("\n------ EULER METHOD ------\n");
    printf("i\t   x\t     y\n");

    printf("%d\t %.4f\t %.4f\n", i, x0, y0);
    // i   x       y
    // 0   0.0000  1.0000


    for (i = 1; i <= n; i++) // 1<=5 2,3,4,5
    {
        // Euler formula
        //#define f(x, y) ((y - x) / (y + x))
        y1 = y0 + h * f(x0, y0);
        //f(x0,y0) = (1 - 0) / (1 + 0) = 1
        //y1 = 1 + 0.02 * 1
        //y1 = 1 + 0.02
        //y1 = 1.0200
        

        //ITERATION 2 (i = 2)
        // f(x0,y0) = (1.02 - 0.02) / (1.02 + 0.02)
        // f(x0,y0) = 1 / 1.04
        // f(x0,y0) = 0.9615

        // y1 = y0 + h * f(x0,y0)
        // y1 = 1.02 + 0.02 * 0.9615
        // y1 = 1.02 + 0.0192
        // y1 = 1.0392

        //  ITERATION 3 (i = 3)

        // f(x0,y0) = (1.0392 - 0.04) / (1.0392 + 0.04)
        // f(x0,y0) = 0.9992 / 1.0792
        // f(x0,y0) = 0.9258

        // y1 = y0 + h * f(x0,y0)
        // y1 = 1.0392 + 0.02 * 0.9258
        // y1 = 1.0392 + 0.0185
        // y1 = 1.0577

        //ITERATION 4 (i = 4)

        // f(x0,y0) = (1.0577 - 0.06) / (1.0577 + 0.06)
        // f(x0,y0) = 0.9977 / 1.1177
        // f(x0,y0) = 0.8926

        // y1 = y0 + h * f(x0,y0)
        // y1 = 1.0577 + 0.02 * 0.8926
        // y1 = 1.0577 + 0.0179
        // y1 = 1.0756

        //ITERATION 5 (i = 5)

        // f(x0,y0) = (1.0756 - 0.08) / (1.0756 + 0.08)
        // f(x0,y0) = 0.9956 / 1.1556
        // f(x0,y0) = 0.8615

        // y1 = y0 + h * f(x0,y0)
        // y1 = 1.0756 + 0.02 * 0.8615
        // y1 = 1.0756 + 0.0172
        // y1 = 1.0929
        x1 = x0 + h;
        //x1 = 0 + 0.02
        //x1 = 0.0200

        //x1 = 0.02 + 0.02
        //x1 = 0.0400

        //x1 = 0.04 + 0.02
        //x1 = 0.0600

        //x1 = 0.06 + 0.02
        //x1 = 0.0800

        //x1 = 0.08 + 0.02
        //x1 = 0.1000
        printf("%d\t %.4f\t %.4f\n", i, x1, y1);
        //x = 0.0200 , y = 1.0200
        //x = 0.0400 , y = 1.0392
        //x = 0.0600 , y = 1.0577
        //x = 0.0800 , y = 1.0756
        //x = 0.1000 , y = 1.0929
        x0 = x1;
        //x0 = 0.0200
        //x0 = 0.0400
        //x0 = 0.0600
        //x0 = 0.0800
        //x0 = 0.1000

        y0 = y1;
        //y0 = 1.0200
        //y0 = 1.0392
        //y0 = 1.0577
        //y0 = 1.0756
        //y0 = 1.0929


    }

    printf("\nFinal value at x = %.4f is y = %.4f\n", x1, y1);
    //Final value at x = 0.1000 is y = 1.0929

    return 0;
}
